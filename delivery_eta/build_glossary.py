from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

FONT_NAME = "맑은 고딕"
TITLE_FONT = Font(name=FONT_NAME, size=16, bold=True, color="FFFFFF")
SUB_FONT = Font(name=FONT_NAME, size=10, italic=True, color="595959")
HEADER_FONT = Font(name=FONT_NAME, size=11, bold=True, color="FFFFFF")
GROUP_FONT = Font(name=FONT_NAME, size=11, bold=True, color="1F4E78")
BODY_FONT = Font(name=FONT_NAME, size=10.5)
TITLE_FILL = PatternFill("solid", fgColor="1F4E78")
HEADER_FILL = PatternFill("solid", fgColor="2E75B6")
GROUP_FILL = PatternFill("solid", fgColor="DCE6F1")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top", horizontal="left")
WRAP_CENTER = Alignment(wrap_text=True, vertical="center", horizontal="center")


def build_sheet(ws, title, subtitle, headers, col_widths, rows, group_col=True):
    ws.merge_cells(f"A1:{chr(64+len(headers))}1")
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws["A1"].fill = TITLE_FILL
    ws["A1"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 30

    ws.merge_cells(f"A2:{chr(64+len(headers))}2")
    ws["A2"] = subtitle
    ws["A2"].font = SUB_FONT
    ws["A2"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 18

    header_row = 4
    for col, h in enumerate(headers, start=1):
        c = ws.cell(row=header_row, column=col, value=h)
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = WRAP_CENTER
        c.border = BORDER
    ws.row_dimensions[header_row].height = 22

    row = header_row + 1
    prev_group = None
    group_start_row = row
    for entry in rows:
        if group_col:
            group, rest, start_col = entry[0], entry[1:], 2
            if group != prev_group and prev_group is not None:
                if row - 1 > group_start_row:
                    ws.merge_cells(f"A{group_start_row}:A{row-1}")
                group_start_row = row
            ws.cell(row=row, column=1, value=group).font = GROUP_FONT
            ws.cell(row=row, column=1).fill = GROUP_FILL
            ws.cell(row=row, column=1).alignment = WRAP_CENTER
            prev_group = group
        else:
            rest, start_col = entry, 1
        for i, val in enumerate(rest):
            col = start_col + i
            cell = ws.cell(row=row, column=col, value=val)
            if col == start_col:
                cell.font = Font(name=FONT_NAME, size=10.5, bold=True)
                cell.alignment = Alignment(wrap_text=True, vertical="top")
            else:
                cell.font = BODY_FONT
                cell.alignment = WRAP
        for col in range(1, len(headers) + 1):
            ws.cell(row=row, column=col).border = BORDER
        row += 1
    if group_col and row - 1 > group_start_row:
        ws.merge_cells(f"A{group_start_row}:A{row-1}")

    for i, w in enumerate(col_widths):
        ws.column_dimensions[chr(65 + i)].width = w
    ws.freeze_panes = "A5"


